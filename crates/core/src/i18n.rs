//! UI strings: English, Russian, Chinese (Simplified), Spanish, French, Portuguese, German.

use std::collections::BTreeMap;
use std::sync::Mutex;
use std::sync::atomic::{AtomicU8, Ordering};

/// Column order of `strings.tsv`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En = 0,
    Ru = 1,
    Zh = 2,
    Es = 3,
    Fr = 4,
    Pt = 5,
    De = 6,
}

impl Lang {
    pub const ALL: [Lang; 7] = [Lang::En, Lang::Ru, Lang::Zh, Lang::Es, Lang::Fr, Lang::Pt, Lang::De];

    /// Value stored in `general.language`.
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Ru => "ru",
            Lang::Zh => "zh",
            Lang::Es => "es",
            Lang::Fr => "fr",
            Lang::Pt => "pt",
            Lang::De => "de",
        }
    }

    /// Name of the language in itself, for the language picker.
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Ru => "Русский",
            Lang::Zh => "中文（简体）",
            Lang::Es => "Español",
            Lang::Fr => "Français",
            Lang::Pt => "Português",
            Lang::De => "Deutsch",
        }
    }

    /// `ru`, `ru-RU`, `pt_BR`… → language; `None` if unsupported.
    pub fn from_code(code: &str) -> Option<Lang> {
        let primary = code.split(['-', '_']).next().unwrap_or("").to_ascii_lowercase();
        Lang::ALL.into_iter().find(|l| l.code() == primary)
    }
}

static LANG: AtomicU8 = AtomicU8::new(0);

/// `setting` is `auto` or a language code; `system_locale` like `ru-RU` is used for `auto` (English if unsupported).
pub fn init(setting: &str, system_locale: &str) {
    let lang = Lang::from_code(setting).or_else(|| Lang::from_code(system_locale)).unwrap_or(Lang::En);
    LANG.store(lang as u8, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    let v = LANG.load(Ordering::Relaxed) as usize;
    Lang::ALL.get(v).copied().unwrap_or(Lang::En)
}

/// Translates `key`; unknown keys are returned unchanged so missing strings are visible but harmless.
pub fn tr(key: &str) -> &'static str {
    tr_in(key, lang())
}

/// `key` in a specific language (the settings search matches every language).
pub fn tr_in(key: &str, lang: Lang) -> &'static str {
    match STRINGS.binary_search_by(|(k, _)| (*k).cmp(key)) {
        Ok(i) => STRINGS[i].1[lang as usize],
        Err(_) => missing(key),
    }
}

/// Interns unknown keys once so `tr` can hand out `'static` strings.
fn missing(key: &str) -> &'static str {
    static MISSING: Mutex<BTreeMap<String, &'static str>> = Mutex::new(BTreeMap::new());
    let mut map = MISSING.lock().unwrap_or_else(|e| e.into_inner());
    if let Some(s) = map.get(key) {
        return s;
    }
    let leaked: &'static str = Box::leak(key.to_string().into_boxed_str());
    map.insert(key.to_string(), leaked);
    leaked
}

/// `tr` with `{0}`, `{1}`… placeholders.
pub fn trf(key: &str, args: &[&str]) -> String {
    let mut s = tr(key).to_string();
    for (i, a) in args.iter().enumerate() {
        s = s.replace(&format!("{{{i}}}"), a);
    }
    s
}

/// (key, one string per `Lang`), sorted by key. Generated by `build.rs` from `strings.tsv`.
static STRINGS: &[(&str, [&str; 7])] = include!(concat!(env!("OUT_DIR"), "/strings.rs"));

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_unique() {
        for w in STRINGS.windows(2) {
            assert!(w[0].0 < w[1].0, "i18n table not sorted/unique at {:?} / {:?}", w[0].0, w[1].0);
        }
    }

    #[test]
    fn language_detection() {
        init("auto", "ru-RU");
        assert_eq!(lang(), Lang::Ru);
        init("auto", "pt_BR");
        assert_eq!(lang(), Lang::Pt);
        init("auto", "ja-JP");
        assert_eq!(lang(), Lang::En, "unsupported locale falls back to English");
        init("de", "ru-RU");
        assert_eq!(lang(), Lang::De, "explicit choice wins over the system locale");
        assert_eq!(tr("menu.exit"), "Beenden");
        assert_eq!(tr_in("menu.exit", Lang::Zh), "退出");
        init("en", "");
    }

    #[test]
    fn every_metric_kind_and_style_has_a_name() {
        for k in crate::metrics::MetricKind::ALL {
            let key = format!("kind.{}", k.key());
            assert!(STRINGS.iter().any(|s| s.0 == key), "missing {key}");
        }
        for s in crate::metrics::MetricStyle::ALL {
            let key = format!("style.{}", s.key());
            assert!(STRINGS.iter().any(|x| x.0 == key), "missing {key}");
        }
    }

    /// Every literal `tr("…")` / `trf("…")` key in the workspace must exist in `strings.tsv`.
    #[test]
    fn all_used_keys_exist() {
        fn scan(dir: &std::path::Path, found: &mut Vec<String>) {
            for entry in std::fs::read_dir(dir).unwrap().flatten() {
                let path = entry.path();
                if path.is_dir() {
                    scan(&path, found);
                } else if path.extension().is_some_and(|e| e == "rs") {
                    let text = std::fs::read_to_string(&path).unwrap();
                    for prefix in ["tr(\"", "trf(\""] {
                        for part in text.split(prefix).skip(1) {
                            if let Some(end) = part.find('"') {
                                let key = &part[..end];
                                if !key.is_empty() && key.chars().all(|c| c.is_ascii_lowercase() || c == '.' || c == '_') {
                                    found.push(key.to_string());
                                }
                            }
                        }
                    }
                }
            }
        }
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let mut keys = Vec::new();
        scan(&root.join("core/src"), &mut keys);
        scan(&root.join("app/src"), &mut keys);
        assert!(keys.len() > 50, "scan found too few keys");
        let missing: Vec<_> = keys.iter().filter(|k| STRINGS.binary_search_by(|(x, _)| (*x).cmp(k.as_str())).is_err()).collect();
        assert!(missing.is_empty(), "missing translations: {missing:?}");
    }
}
