//! English and Russian UI strings.

use std::collections::BTreeMap;
use std::sync::Mutex;
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En = 0,
    Ru = 1,
}

static LANG: AtomicU8 = AtomicU8::new(0);

/// `setting` is `auto`, `en` or `ru`; `system_locale` like `ru-RU` is used for `auto`.
pub fn init(setting: &str, system_locale: &str) {
    let lang = match setting {
        "ru" => Lang::Ru,
        "en" => Lang::En,
        _ if system_locale.to_lowercase().starts_with("ru") => Lang::Ru,
        _ => Lang::En,
    };
    LANG.store(lang as u8, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    if LANG.load(Ordering::Relaxed) == 1 { Lang::Ru } else { Lang::En }
}

/// Translates `key`; unknown keys are returned unchanged so missing strings are visible but harmless.
pub fn tr(key: &str) -> &'static str {
    match STRINGS.binary_search_by(|(k, _, _)| (*k).cmp(key)) {
        Ok(i) => match lang() {
            Lang::En => STRINGS[i].1,
            Lang::Ru => STRINGS[i].2,
        },
        Err(_) => missing(key),
    }
}

/// Interns unknown keys once so `tr` can hand out `'static` strings.
fn missing(key: &str) -> &'static str {
    static MISSING: Mutex<BTreeMap<String, &'static str>> = Mutex::new(BTreeMap::new());
    let mut map = MISSING.lock().unwrap_or_else(|e| e.into_inner());
    if let Some(s) = map.get(key) {
        return s;
    }
    let leaked: &'static str = Box::leak(key.to_string().into_boxed_str());
    map.insert(key.to_string(), leaked);
    leaked
}

/// `tr` with `{0}`, `{1}`… placeholders.
pub fn trf(key: &str, args: &[&str]) -> String {
    let mut s = tr(key).to_string();
    for (i, a) in args.iter().enumerate() {
        s = s.replace(&format!("{{{i}}}"), a);
    }
    s
}

/// (key, English, Russian), sorted by key. Generated by `build.rs` from `strings.tsv`.
static STRINGS: &[(&str, &str, &str)] = include!(concat!(env!("OUT_DIR"), "/strings.rs"));

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_unique() {
        for w in STRINGS.windows(2) {
            assert!(w[0].0 < w[1].0, "i18n table not sorted/unique at {:?} / {:?}", w[0].0, w[1].0);
        }
    }

    #[test]
    fn every_metric_kind_and_style_has_a_name() {
        for k in crate::metrics::MetricKind::ALL {
            let key = format!("kind.{}", k.key());
            assert!(STRINGS.iter().any(|s| s.0 == key), "missing {key}");
        }
        for s in crate::metrics::MetricStyle::ALL {
            let key = format!("style.{}", s.key());
            assert!(STRINGS.iter().any(|x| x.0 == key), "missing {key}");
        }
    }

    /// Every literal `tr("…")` / `trf("…")` key in the workspace must exist in `strings.tsv`.
    #[test]
    fn all_used_keys_exist() {
        fn scan(dir: &std::path::Path, found: &mut Vec<String>) {
            for entry in std::fs::read_dir(dir).unwrap().flatten() {
                let path = entry.path();
                if path.is_dir() {
                    scan(&path, found);
                } else if path.extension().is_some_and(|e| e == "rs") {
                    let text = std::fs::read_to_string(&path).unwrap();
                    for prefix in ["tr(\"", "trf(\""] {
                        for part in text.split(prefix).skip(1) {
                            if let Some(end) = part.find('"') {
                                let key = &part[..end];
                                if !key.is_empty() && key.chars().all(|c| c.is_ascii_lowercase() || c == '.' || c == '_') {
                                    found.push(key.to_string());
                                }
                            }
                        }
                    }
                }
            }
        }
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let mut keys = Vec::new();
        scan(&root.join("core/src"), &mut keys);
        scan(&root.join("app/src"), &mut keys);
        assert!(keys.len() > 50, "scan found too few keys");
        let missing: Vec<_> =
            keys.iter().filter(|k| STRINGS.binary_search_by(|(x, _, _)| (*x).cmp(k.as_str())).is_err()).collect();
        assert!(missing.is_empty(), "missing translations: {missing:?}");
    }
}
